//! The spec suite: what a second implementation is held to.
//!
//! Everything else in `tests/` checks this crate against itself. This file checks it against
//! `spec/v1/`, which is the artefact a Java or Spring Boot producer conforms to and the only thing
//! standing between two implementations and two subtly different documents.
//!
//! It has two halves, and they fail for different reasons:
//!
//! - **The meta-schema** ([`spec/v1/contract.schema.json`]) says what a well-formed contract is.
//!   A failure here means this crate emits something the spec does not describe — either the
//!   crate grew a field the spec has not learned, or the spec claims something the crate never
//!   guaranteed. Both are the spec being wrong, because the spec is what another language reads.
//! - **The conformance corpus** (`spec/v1/conformance/`) says what one specific input produces.
//!   A failure here means a rendering changed. That is sometimes intended — regenerate with
//!   `TERRACE_SPEC_BLESS=1 cargo test --all-features --test spec` and read the diff, which is the
//!   point: the diff is the change a second implementation now has to match.
//!
//! The corpus is checked against the meta-schema too. A case that no longer validates is the one
//! failure mode a corpus alone cannot catch: an expectation that was blessed while wrong.

#![cfg(feature = "schema")]
#![expect(dead_code, reason = "fixtures are read by the derive, not at runtime")]

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use serde_json::{Value as Json, json};
use terrace_config::Terrace;
use terrace_config::schema::{App, Contract, Describe, External, ExternalVar, Unknown};

/// The version string every corpus document carries in place of the real one.
///
/// The producer's version moves on every release and says nothing about the rendering, so leaving
/// it in would make each release a corpus-wide diff that hides the one line that mattered. A
/// sentinel rather than the real number, because a reference document carrying a version it was
/// not generated by is a small lie a reader has no way to detect.
const CONFORMANCE_VERSION: &str = "0.0.0-conformance";

/// Set to regenerate the corpus instead of checking it.
const BLESS: &str = "TERRACE_SPEC_BLESS";

fn spec_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("spec")
        .join("v1")
}

// ---------------------------------------------------------------------------------------------
// Fixtures
//
// One per case, and deliberately not shared: a corpus case is a claim about what a specific input
// renders to, so a fixture edited for one case's sake would silently restate every other case.
// ---------------------------------------------------------------------------------------------

/// The smallest thing that is still a contract: one key, one layer, nothing annotated.
#[derive(Deserialize, Serialize, Describe)]
struct Minimal {
    /// Bundle directory the readiness probe checks.
    #[serde(default = "default_dist")]
    dist_dir: String,
}

// Hand-written rather than derived, in every fixture here, and it is not boilerplate: the
// *observed* default is what `with_defaults_from` serialises, so a derived `Default` would publish
// `""` for a field whose `#[serde(default = "…")]` supplies `public`. A corpus document is read by
// somebody implementing this in another language, and one whose defaults contradict its own
// annotations teaches the wrong thing.
impl Default for Minimal {
    fn default() -> Self {
        Self {
            dist_dir: default_dist(),
        }
    }
}

/// Every field of a key that a producer can be asked to fill.
#[derive(Deserialize, Serialize, Describe)]
#[serde(deny_unknown_fields)]
struct Full {
    /// Bundle directory the readiness probe checks.
    #[serde(default = "default_dist")]
    dist_dir: String,
    /// Base URL every outbound request is resolved against.
    ///
    /// No default and not optional, so some layer has to supply it — which is what `required`
    /// says, and which is not what a JSON Schema `required` list would say about the rendered
    /// document.
    api_base: String,
    /// How much the service says.
    #[config(values)]
    #[serde(default)]
    log_level: LogLevel,
    /// Fraction of requests sampled for tracing.
    #[config(range(min = 0.0, max = 1.0))]
    #[serde(default)]
    sample_rate: f64,
    /// Methods every route admits.
    #[config(element_values)]
    #[serde(default)]
    methods: Vec<Method>,
    #[config(nested)]
    github: Github,
}

impl Default for Full {
    fn default() -> Self {
        Self {
            dist_dir: default_dist(),
            // No `#[serde(default)]`, so no layer-independent value exists and the key is
            // `required`. What this field holds here is never published: a required key renders
            // `default: null`, which is the assertion `full-surface` pins.
            api_base: String::new(),
            log_level: LogLevel::default(),
            sample_rate: 0.0,
            methods: Vec::new(),
            github: Github::default(),
        }
    }
}

#[derive(Deserialize, Serialize, Default, Describe)]
struct Github {
    /// User whose repositories are listed.
    #[serde(alias = "user")]
    username: String,
    /// Bearer token lifting the API rate limit.
    ///
    /// Supply it as a mounted file, so the value never reaches the process environment.
    #[config(secret)]
    token: Option<String>,
    /// Revalidation interval in seconds.
    #[config(note = "permanent")]
    #[serde(default)]
    ttl_secs: u64,
}

/// A container whose keys the environment cannot name.
///
/// `rename_all = "camelCase"` is the ordinary way to arrive here: the environment layer folds a
/// name to lower case on the way in, and a camel-cased path never comes back through the fold. The
/// key is real and the document can supply it; no variable can, and `unreachable` is what says
/// which of those two situations a consumer is looking at.
#[derive(Deserialize, Serialize, Describe)]
#[serde(rename_all = "camelCase")]
struct Unnameable {
    /// Where the bundle is read from.
    #[serde(default = "default_dist")]
    dist_dir: String,
    /// How long a rendered page stays fresh.
    #[serde(default)]
    max_age_secs: u64,
}

impl Default for Unnameable {
    fn default() -> Self {
        Self {
            dist_dir: default_dist(),
            max_age_secs: 0,
        }
    }
}

#[derive(Deserialize, Serialize, Default, Describe)]
#[serde(rename_all = "lowercase")]
enum LogLevel {
    Trace,
    Debug,
    #[default]
    Info,
    Warn,
}

#[derive(Deserialize, Serialize, Default, Describe)]
#[serde(rename_all = "UPPERCASE")]
enum Method {
    #[default]
    Get,
    Post,
}

fn default_dist() -> String {
    "public".to_owned()
}

