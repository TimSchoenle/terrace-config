#[test]
fn the_producer_names_itself_and_its_loader() {
    let json = as_json(&minimal());

    assert_eq!(json["producer"]["name"], json!("terrace-config"));
    // The field a consumer needs before it applies any `text_constraint`: those patterns were
    // measured against this library's environment reads and describe no other.
    assert_eq!(json["producer"]["loader"], json!("figment"));
}

#[test]
fn a_key_the_environment_cannot_name_says_why() {
    // The invariant the meta-schema encodes as a conditional. It holds because a producer that
    // publishes no spelling always has a reason to publish, and a consumer meeting a bare null
    // would have to guess between "the document is the only layer" and "another key's variable
    // fills this one".
    let json = as_json(&unnameable_key());
    let keys = json["schema"]["keys"].as_array().expect("keys is an array");

    let unnameable: Vec<_> = keys.iter().filter(|key| key["env"].is_null()).collect();
    assert!(
        !unnameable.is_empty(),
        "the fixture is supposed to produce a key no variable names"
    );
    for key in unnameable {
        assert_eq!(key["unreachable"], json!("unnameable"), "{key}");
    }
}
