/// Every corpus case, by directory name.
///
/// The `App` is fixed rather than derived: `revision` and `created` are build facts, and a corpus
/// carrying them would be a corpus that changes on every run.
fn cases() -> Vec<(&'static str, Contract)> {
    vec![
        ("minimal", minimal()),
        ("full-surface", full_surface()),
        ("unnameable-key", unnameable_key()),
    ]
}

fn minimal() -> Contract {
    Terrace::new("MINIMAL_")
        .schema::<Minimal>()
        .with_defaults_from(&Minimal::default())
        .expect("the default config serialises")
        .into_contract(App::new("minimal").version("1.0.0"))
        .build()
        .expect("the contract has nothing to refuse")
}

fn full_surface() -> Contract {
    Terrace::new("PORTFOLIO_")
        .reserve("PORTFOLIO_PROFILE")
        .schema::<Full>()
        .with_defaults_from(&Full::default())
        .expect("the default config serialises")
        .into_contract(App::new("portfolio").version("2.5.0"))
        .external(
            External::new()
                .var(
                    ExternalVar::new("PORT")
                        .owner("runtime")
                        .ty("u16")
                        .default("8080")
                        .docs("Bind port. Read by the server toolchain, not by this loader."),
                )
                .var(ExternalVar::new("RUST_LOG").owner("tracing").ty("String"))
                .ignore("KUBERNETES_*")
                .ignore("HOSTNAME")
                .unknown(Unknown::Reject),
        )
        .build()
        .expect("the contract has nothing to refuse")
}

fn unnameable_key() -> Contract {
    Terrace::new("EDGE_")
        .schema::<Unnameable>()
        .with_defaults_from(&Unnameable::default())
        .expect("the default config serialises")
        .into_contract(App::new("edge").version("1.0.0"))
        .build()
        .expect("the contract has nothing to refuse")
}

// ---------------------------------------------------------------------------------------------
// The meta-schema
// ---------------------------------------------------------------------------------------------

fn meta_schema() -> Json {
    let path = spec_dir().join("contract.schema.json");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{} could not be read: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{} is not JSON: {e}", path.display()))
}

fn validator(schema: &Json) -> jsonschema::Validator {
    jsonschema::validator_for(schema).expect("the meta-schema is a valid JSON Schema")
}

/// The meta-schema restricted to its `schema` half, for the `json` rendering.
///
/// Built by pointing the root at `#/$defs/schema` rather than by resolving
/// `contract.schema.json#schema` through a registry: the definitions are in the same document, so
/// a local pointer reaches them, and a test that needed a resolver would be testing the resolver.
fn schema_half_validator(meta: &Json) -> jsonschema::Validator {
    let mut sub = meta.clone();
    let object = sub.as_object_mut().expect("the meta-schema is an object");
    for key in ["type", "properties", "required", "title", "description"] {
        object.remove(key);
    }
    object.insert(
        "$id".to_owned(),
        json!("https://terrace.dev/spec/v1/schema-only.json"),
    );
    object.insert("$ref".to_owned(), json!("#/$defs/schema"));
    validator(&sub)
}

fn assert_valid(validator: &jsonschema::Validator, instance: &Json, what: &str) {
    let errors: Vec<String> = validator
        .iter_errors(instance)
        .map(|e| format!("  at `{}`: {e}", e.instance_path()))
        .collect();
    assert!(
        errors.is_empty(),
        "{what} does not satisfy spec/v1/contract.schema.json:\n{}",
        errors.join("\n")
    );
}

#[test]
fn the_meta_schema_is_itself_a_valid_json_schema() {
    // Compiling it is the check. A meta-schema with a dangling `$ref` or a misspelt keyword
    // validates everything silently, which is worse than validating nothing.
    let _ = validator(&meta_schema());
}

#[test]
fn every_case_satisfies_the_meta_schema() {
    let meta = meta_schema();
    let validator = validator(&meta);

    for (name, contract) in cases() {
        let json = as_json(&contract);
        assert_valid(&validator, &json, &format!("the `{name}` case"));
    }
}

#[test]
fn the_schema_half_satisfies_the_meta_schema_on_its_own() {
    // The `json` rendering is published as an artefact of its own, so the subschema has to be
    // reachable and correct without the envelope around it.
    let validator = schema_half_validator(&meta_schema());

    for (name, contract) in cases() {
        let json = serde_json::to_value(&contract.schema).expect("the schema half serialises");
        assert_valid(
            &validator,
            &json,
            &format!("the `{name}` case's schema half"),
        );
    }
}

#[test]
fn the_stored_corpus_satisfies_the_meta_schema() {
    // Not the same check as `every_case_satisfies_the_meta_schema`: that one validates what the
    // crate renders *now*, this one validates what was blessed. An expectation blessed while
    // wrong passes the first and fails here.
    let validator = validator(&meta_schema());

    for (name, _) in cases() {
        let path = case_path(name);
        let Ok(text) = std::fs::read_to_string(&path) else {
            continue; // `the_corpus_matches_what_the_crate_renders` is what reports a missing case.
        };
        let json: Json = serde_json::from_str(&text)
            .unwrap_or_else(|e| panic!("{} is not JSON: {e}", path.display()));
        assert_valid(&validator, &json, &format!("the stored `{name}` case"));
    }
}

// ---------------------------------------------------------------------------------------------
// The corpus
// ---------------------------------------------------------------------------------------------

fn case_path(name: &str) -> PathBuf {
    spec_dir()
        .join("conformance")
        .join(name)
        .join("contract.json")
}

/// The document with the one field a corpus cannot pin: see [`CONFORMANCE_VERSION`].
///
/// Substituted on the `Contract` rather than on the JSON it renders to, so that the stored file is
/// what `to_json` actually emits — same field order, same bytes. Round-tripping through
/// `serde_json::Value` sorts every object alphabetically, which would leave the corpus full of
/// documents no producer ever writes and no reader should imitate.
fn normalise(contract: &Contract) -> Contract {
    let mut contract = contract.clone();
    CONFORMANCE_VERSION.clone_into(&mut contract.producer.version);
    contract
}

fn rendered(contract: &Contract) -> String {
    let mut text = normalise(contract).to_json().expect("the contract renders");
    text.push('\n');
    text
}

/// The stored document, parsed — for the checks that validate rather than compare.
fn as_json(contract: &Contract) -> Json {
    serde_json::from_str(&rendered(contract)).expect("the rendered contract parses")
}

#[test]
fn the_corpus_matches_what_the_crate_renders() {
    let bless = std::env::var_os(BLESS).is_some();
    let mut stale: BTreeMap<&str, String> = BTreeMap::new();

    for (name, contract) in cases() {
        let path = case_path(name);
        let expected = rendered(&contract);

        if bless {
            std::fs::create_dir_all(path.parent().expect("the case has a directory"))
                .expect("the case directory can be created");
            std::fs::write(&path, expected.as_bytes()).expect("the case can be written");
            continue;
        }

        match std::fs::read_to_string(&path) {
            Ok(found) => {
                let found = found.replace("\r\n", "\n");
                if found != expected {
                    stale.insert(name, first_difference(&found, &expected));
                }
            }
            Err(e) => {
                stale.insert(name, format!("could not be read: {e}"));
            }
        }
    }

    let mut report = String::new();
    for (name, detail) in &stale {
        write!(report, "\n`{name}`: {detail}").expect("writing to a String cannot fail");
    }

    assert!(
        stale.is_empty(),
        "the conformance corpus no longer matches what this crate renders. If the change is \
         intended, regenerate with `{BLESS}=1 cargo test --all-features --test spec` and read the \
         diff — it is the change every other implementation now has to match.\n{report}"
    );
}

/// The first line the two differ on, which is what a reader needs and what a whole-document dump
/// buries.
fn first_difference(found: &str, expected: &str) -> String {
    for (line, (a, b)) in found.lines().zip(expected.lines()).enumerate() {
        if a != b {
            return format!("line {}: stored `{a}`, rendered `{b}`", line + 1);
        }
    }
    format!(
        "stored document has {} lines, rendered has {}",
        found.lines().count(),
        expected.lines().count()
    )
}

